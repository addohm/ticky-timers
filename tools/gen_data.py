"""Generate Ticky/Data.lua from WoW: Forever DB2 CSV exports (wago.tools, build given on the CLI).

usage: python gen_data.py <csv dir> <build> <out Data.lua>
"""
import csv, sys, collections

src, build, out = sys.argv[1], sys.argv[2], sys.argv[3]
def rows(n): return list(csv.DictReader(open(f"{src}/{n}.csv", encoding="utf-8")))

# Which spells belong to player classes: class spell families 3..11 (mage..shaman),
# plus spells taught on class/racial skill lines.
CLASS_SETS = {str(i) for i in range(3, 12)}
class_spells = {r["SpellID"] for r in rows("SpellClassOptions") if r["SpellClassSet"] in CLASS_SETS}
skill = {r["ID"]: r for r in rows("SkillLine")}
def player_line(sid):
    s = skill.get(sid)
    if not s: return False
    name = s["DisplayName_lang"]
    if s["CategoryID"] == "7":
        return not (name.startswith("Pet - ") or name in ("Mounts", "Companions"))
    return s["CategoryID"] == "11" and "racial" in name.lower()
for r in rows("SkillLineAbility"):
    if player_line(r["SkillLine"]): class_spells.add(r["Spell"])

names = {r["ID"]: r["Name_lang"] for r in rows("SpellName")}
durations = {r["ID"]: int(r["Duration"]) for r in rows("SpellDuration")}
misc = {}
for r in rows("SpellMisc"):
    if r["DifficultyID"] == "0": misc[r["SpellID"]] = r

AURA_EFFECTS = {"6", "35", "65", "119", "128", "129", "143"}  # apply aura / area auras
# Aura types that tick: damage, heal, obs health/power, trigger, energize, leech, funnel,
# mana leech, damage %, dummy.
PERIODIC = {"3": 0, "8": 0, "53": 0, "62": 0, "64": 0, "89": 0, "20": 1, "21": 1, "24": 1, "23": 2, "226": 3}

effects = collections.defaultdict(list)
for r in rows("SpellEffect"):
    if r["DifficultyID"] == "0" and r["SpellID"] in class_spells:
        effects[r["SpellID"]].append(r)

data = {}
stats = collections.Counter()
for sid, effs in effects.items():
    m = misc.get(sid)
    if not m: continue
    if not any(e["Effect"] in AURA_EFFECTS for e in effs): continue
    dur = durations.get(m["DurationIndex"], 0)
    a1, a5 = int(m["Attributes_1"]), int(m["Attributes_5"])
    channel = bool(a1 & 0x4 or a1 & 0x40)
    if dur <= 0 and not channel: continue  # permanent buffs have no timer to show
    entry = {}
    ticking = [e for e in effs if e["EffectAura"] in PERIODIC and int(e["EffectAuraPeriod"]) > 0]
    if ticking:
        best = min(ticking, key=lambda e: (PERIODIC[e["EffectAura"]], int(e["EffectIndex"])))
        entry["p"] = int(best["EffectAuraPeriod"])
        if a5 & 0x2000: entry["h"] = True   # SPELL_ATTR5_SPELL_HASTE_AFFECTS_PERIODIC
        if channel and dur > 0: entry["d"] = dur
        stats["ticking"] += 1
    else:
        stats["aura only"] += 1
    if channel: stats["channel"] += 1
    data[int(sid)] = entry

lines = [
    "-- Generated by tools/gen_data.py from World of Warcraft: Forever spell tables",
    f"-- (wago.tools, build {build}: SpellEffect, SpellMisc, SpellDuration, SpellClassOptions,",
    "-- SkillLineAbility, SkillLine, SpellName). Do not edit by hand; regenerate instead.",
    "--",
    "-- ns.Data[spellID] lists every class spell that puts a timed buff or debuff on something.",
    "--   p = tick period in milliseconds (only for spells that tick)",
    "--   h = true if haste shortens the period",
    "--   d = channel base duration in milliseconds (spreads a channel's ticks over its hasted length)",
    "local _, ns = ...",
    "",
    "ns.DataBuild = \"%s\"" % build,
    "ns.Data = {",
]
for sid in sorted(data):
    e = data[sid]
    parts = []
    if "p" in e: parts.append(f"p={e['p']}")
    if e.get("h"): parts.append("h=true")
    if "d" in e: parts.append(f"d={e['d']}")
    lines.append(f"  [{sid}]={{{','.join(parts)}}}, -- {names.get(str(sid), '?')}")
lines.append("}")
open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print(f"{len(data)} spells ({stats['ticking']} ticking, {stats['aura only']} aura only, {stats['channel']} channels)")
